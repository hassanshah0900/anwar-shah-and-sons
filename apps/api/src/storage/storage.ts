import type { Readable } from 'node:stream';

export type StoredObject = {
  body: Readable;
  contentType: string;
  size?: number;
};

/**
 * Where uploaded media lives. Keys are relative paths such as
 * products/<id>/<file>.webp; drivers decide how they map to storage.
 */
export abstract class StorageService {
  abstract put(key: string, body: Buffer, contentType: string): Promise<void>;
  /** Resolves to null when the key doesn't exist. */
  abstract get(key: string): Promise<StoredObject | null>;
  /** Succeeds when the key is already gone. */
  abstract delete(key: string): Promise<void>;
}

const KEY_PATTERN = /^[a-z0-9]+(?:[/._-][a-z0-9]+)*$/i;

/** Keys are generated by the API, but check them anyway: no traversal, no absolute paths. */
export function assertValidKey(key: string): void {
  if (!KEY_PATTERN.test(key) || key.includes('..')) {
    throw new Error(`Invalid storage key: ${key}`);
  }
}

const extensions: Record<string, string> = {
  'image/jpeg': 'jpg',
  'image/png': 'png',
  'image/webp': 'webp',
  'image/avif': 'avif',
};

export function extensionFor(contentType: string): string {
  const extension = extensions[contentType];
  if (!extension) throw new Error(`Unsupported content type: ${contentType}`);
  return extension;
}

export function contentTypeFor(key: string): string {
  const extension = key.split('.').pop() ?? '';
  return (
    Object.entries(extensions).find(([, value]) => value === extension)?.[0] ??
    'application/octet-stream'
  );
}
